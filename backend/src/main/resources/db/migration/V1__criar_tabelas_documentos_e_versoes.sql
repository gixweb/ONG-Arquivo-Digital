-- V1: Criação das tabelas centrais do Arquivo Digital da ONG

CREATE TABLE documentos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo VARCHAR(255) NOT NULL,
    tipo VARCHAR(50) NOT NULL,
    data_documento DATE NOT NULL,
    responsavel VARCHAR(150) NOT NULL,
    status VARCHAR(50) NOT NULL DEFAULT 'vigente',
    versao_atual INT NOT NULL DEFAULT 1,
    criado_em TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atualizado_em TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_documento_tipo CHECK (tipo IN ('ata', 'contrato', 'relatorio', 'oficio')),
    CONSTRAINT chk_documento_status CHECK (status IN ('vigente', 'arquivado'))
);

CREATE TABLE versoes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    documento_id BIGINT NOT NULL,
    numero INT NOT NULL,
    observacao VARCHAR(500) NOT NULL,
    blob_nome VARCHAR(255),
    criada_em TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_versoes_documento FOREIGN KEY (documento_id) REFERENCES documentos(id) ON DELETE CASCADE,
    CONSTRAINT uq_documento_versao UNIQUE (documento_id, numero)
);

CREATE INDEX idx_documentos_tipo_data ON documentos(tipo, data_documento);
CREATE INDEX idx_documentos_titulo ON documentos(titulo);
CREATE INDEX idx_versoes_documento_id ON versoes(documento_id);
